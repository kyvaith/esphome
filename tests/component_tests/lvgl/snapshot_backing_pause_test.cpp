struct LvglComponent;
struct lv_display_t {
  LvglComponent *user_data;
  bool invalidation{true};
};
struct lv_obj_t {
  lv_display_t *display;
};
struct lv_draw_buf_t {
  struct {
    uint32_t w{16};
    uint32_t h{16};
  } header;
};

static constexpr size_t SNAPSHOT_TILE_SLOT_COUNT = 3;
static const char *const TAG = "test";
static std::vector<std::string> trace;
static unsigned initial_depth;
static bool drain_result{true};
static bool snapshot_active;
static bool capture_result{true};
static bool target_encode_result{true};
static bool outgoing_encode_result{true};
static bool restore_result{true};
static bool cache_valid{true};
static int slot_index;
static unsigned operations;
static unsigned restore_calls;
static unsigned warnings;

struct LvglComponent {
  unsigned depth{};
  bool drained{};
  bool direct_regions_pause(bool pause, uint32_t timeout) {
    if (pause) {
      assert(timeout == 120);
      assert(this->depth == initial_depth);
      this->depth++;
      this->drained = drain_result;
      trace.emplace_back("pause");
      return drain_result;
    }
    assert(timeout == 0);
    assert(this->depth == initial_depth + 1);
    this->depth--;
    trace.emplace_back("resume");
    return true;
  }
} component;

static lv_display_t display{&component};
static lv_obj_t target{&display};
static lv_obj_t resident{&display};
static lv_draw_buf_t pixels;
static lv_draw_buf_t *snapshot_app_work_buf;
static lv_obj_t *snapshot_app_work_obj;
static struct {
  std::array<lv_draw_buf_t *, SNAPSHOT_TILE_SLOT_COUNT> slots{};
  std::array<lv_obj_t *, SNAPSHOT_TILE_SLOT_COUNT> pages{};
  std::array<lv_obj_t *, SNAPSHOT_TILE_SLOT_COUNT> restore_pages{};
  std::array<bool, SNAPSHOT_TILE_SLOT_COUNT> busy{};
  std::array<bool, SNAPSHOT_TILE_SLOT_COUNT> dirty{};
  int height{16};
} snapshot_tile_window_cache;

static void check_live_lease(const char *operation) {
  assert(component.depth == initial_depth + 1 && component.drained);
  operations++;
  trace.emplace_back(operation);
}
static bool lvgl_esphome_snapshot_is_active() { return snapshot_active; }
static int snapshot_tile_window_slot_index(lv_obj_t *) { return slot_index; }
static void *snapshot_tile_cache_entry(lv_obj_t *, bool) { return &resident; }
static bool snapshot_tile_cache_valid(void *, int, int) { return cache_valid; }
static bool snapshot_tile_cache_encode(lv_obj_t *page, lv_draw_buf_t *) {
  check_live_lease(page == &target ? "encode-target" : "encode-outgoing");
  return page == &target ? target_encode_result : outgoing_encode_result;
}
static lv_display_t *lv_obj_get_display(lv_obj_t *page) { return page->display; }
static void *lv_display_get_user_data(lv_display_t *disp) { return disp->user_data; }
static bool lv_display_is_invalidation_enabled(lv_display_t *disp) { return disp->invalidation; }
static void lv_display_enable_invalidation(lv_display_t *disp, bool enabled) {
  check_live_lease(enabled ? "invalidation-on" : "invalidation-off");
  disp->invalidation = enabled;
}
static bool snapshot_take_centered_to(lv_obj_t *, lv_draw_buf_t *) {
  check_live_lease("capture");
  return capture_result;
}
static bool snapshot_tile_window_load_page(lv_obj_t *page, size_t slot, int, uint32_t) {
  check_live_lease("restore");
  restore_calls++;
  assert(!snapshot_tile_window_cache.busy[slot]);
  assert(snapshot_tile_window_cache.pages[slot] == nullptr);
  assert(snapshot_tile_window_cache.restore_pages[slot] == page);
  if (restore_result) {
    snapshot_tile_window_cache.pages[slot] = page;
    snapshot_tile_window_cache.restore_pages[slot] = nullptr;
  }
  return restore_result;
}
template<typename... Ts> static void ESP_LOGW(const char *, const char *, Ts...) { warnings++; }

// This file is generated by the Python test from the actual firmware source.
#include "snapshot_backing_under_test.inc"

static void reset(unsigned nesting = 0) {
  initial_depth = nesting;
  component = {nesting, false};
  display = {&component, true};
  target.display = &display;
  drain_result = capture_result = target_encode_result = outgoing_encode_result = restore_result = cache_valid = true;
  snapshot_active = false;
  slot_index = 0;
  operations = restore_calls = warnings = 0;
  pixels.header = {16, 16};
  snapshot_tile_window_cache = {};
  snapshot_tile_window_cache.height = 16;
  snapshot_tile_window_cache.slots[0] = &pixels;
  snapshot_tile_window_cache.pages[0] = &target;
  snapshot_app_work_buf = nullptr;
  snapshot_app_work_obj = &target;
  trace.clear();
}
static void borrowed() {
  slot_index = -1;
  snapshot_tile_window_cache.slots[0] = nullptr;
  snapshot_tile_window_cache.pages[0] = nullptr;
  snapshot_tile_window_cache.slots[2] = &pixels;
  snapshot_tile_window_cache.pages[2] = &resident;
}
static void balanced(bool attempted = true) {
  assert(component.depth == initial_depth);
  if (!attempted) {
    assert(trace.empty());
    return;
  }
  assert(trace.front() == "pause" && trace.back() == "resume");
  unsigned pauses = 0, resumes = 0;
  for (const auto &item : trace) {
    pauses += item == "pause";
    resumes += item == "resume";
  }
  assert(pauses == 1 && resumes == 1);
}

int main(int argc, char **argv) {
  assert(argc == 2);
  const int test = std::atoi(argv[1]);
  reset();
  switch (test) {
    case 0:  // Resident capture and encode finish before releasing the lease.
      assert(lvgl_esphome_snapshot_refresh_tile_backing(&target, 16));
      assert(!snapshot_tile_window_cache.dirty[0] && display.invalidation);
      balanced();
      break;
    case 1:
      capture_result = false;
      assert(!lvgl_esphome_snapshot_refresh_tile_backing(&target, 16));
      assert(snapshot_tile_window_cache.dirty[0] && display.invalidation);
      assert(operations == 3);  // Disable, failed capture, restore invalidation.
      balanced();
      break;
    case 2:
      target_encode_result = false;
      assert(!lvgl_esphome_snapshot_refresh_tile_backing(&target, 16));
      assert(snapshot_tile_window_cache.dirty[0] && display.invalidation);
      balanced();
      break;
    case 3:  // The real pause API increments depth before a failed wait.
    case 5:
      reset(test == 5 ? 2 : 0);
      drain_result = false;
      assert(!lvgl_esphome_snapshot_refresh_tile_backing(&target, 16));
      assert(operations == 0 && display.invalidation);
      assert(snapshot_tile_window_cache.pages[0] == &target && snapshot_app_work_obj == &target);
      balanced();
      break;
    case 4:
      reset(2);
      assert(lvgl_esphome_snapshot_refresh_tile_backing(&target, 16));
      balanced();
      break;
    case 6:
    case 8:
    case 9:
      borrowed();
      capture_result = test != 8;
      restore_result = test != 9;
      assert(lvgl_esphome_snapshot_refresh_tile_backing(&target, 16) == (test == 6));
      assert(restore_calls == 1);
      assert(snapshot_tile_window_cache.pages[2] == (restore_result ? &resident : nullptr));
      assert(snapshot_tile_window_cache.restore_pages[2] == (restore_result ? nullptr : &resident));
      assert(warnings == (test == 9 ? 1U : 0U));
      assert(trace[trace.size() - 2] == "restore");
      balanced();
      break;
    case 7:
      borrowed();
      snapshot_tile_window_cache.dirty[2] = true;
      outgoing_encode_result = false;
      assert(!lvgl_esphome_snapshot_refresh_tile_backing(&target, 16));
      assert(operations == 1 && restore_calls == 0);
      assert(snapshot_tile_window_cache.pages[2] == &resident && snapshot_tile_window_cache.dirty[2]);
      balanced();
      break;
    case 10:
      for (bool missing : {true, false}) {
        reset();
        if (missing)
          snapshot_tile_window_cache.slots[0] = nullptr;
        else
          pixels.header.w = 17;
        assert(!lvgl_esphome_snapshot_refresh_tile_backing(&target, 16));
        assert(operations == 0);
        balanced();
      }
      break;
    case 11:
      for (unsigned invalid = 0; invalid < 6; invalid++) {
        reset();
        if (invalid == 2)
          snapshot_active = true;
        if (invalid == 3)
          snapshot_tile_window_cache.busy[1] = true;
        if (invalid == 4)
          target.display = nullptr;
        if (invalid == 5)
          display.user_data = nullptr;
        assert(!lvgl_esphome_snapshot_refresh_tile_backing(invalid == 0 ? nullptr : &target, invalid == 1 ? 0 : 16));
        assert(operations == 0);
        balanced(false);
      }
      break;
    case 12:
      slot_index = -1;
      display.invalidation = false;
      snapshot_app_work_buf = &pixels;
      assert(lvgl_esphome_snapshot_refresh_tile_backing(&target, 16));
      assert(snapshot_app_work_obj == nullptr && !display.invalidation && restore_calls == 0);
      balanced();
      break;
    default:
      return 2;
  }
  std::printf("case %d PASS\n", test);
}
